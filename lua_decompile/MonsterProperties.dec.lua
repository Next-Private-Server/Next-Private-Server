  xOffset = 0,
  yOffset = 0,
  scale = 1
}
function MonsterProperties.getIdleViewBounds(monsterId, animWidth, animHeight, targetWidth, targetHeight)
  local boundsInfo = {
    xOffset = 0,
    yOffset = 0,
    scale = 1
  }
  if props[monsterId] and props[monsterId].view_bounds then
    local viewBounds = props[monsterId].view_bounds
    local scaleW = targetWidth / viewBounds.w
    local scaleH = targetHeight / viewBounds.h
    boundsInfo.scale = scaleW > scaleH and scaleH or scaleW
    boundsInfo.xOffset = viewBounds.x * boundsInfo.scale
    boundsInfo.yOffset = viewBounds.y * boundsInfo.scale
  else
    local monsterData = game.getMonsterById(monsterId)
    local scaleMod = 2.5
    local scaleW = targetWidth / animWidth
    local scaleH = targetHeight / animHeight
    boundsInfo.scale = (scaleW > scaleH and scaleH or scaleW) * scaleMod
    local gridSize = monsterData:gridSize()
    local monsterHeight = monsterData:yOffset()
    boundsInfo.yOffset = monsterHeight * 0.66 * boundsInfo.scale
  end
  return boundsInfo
end
function MonsterProperties.scaleIdle(monsterId, animComponent, targetWidth, targetHeight)
  local viewBounds = MonsterProperties.getIdleViewBounds(monsterId, animComponent:absW(), animComponent:absH(), targetWidth, targetHeight)
  animComponent:setScale(Vector2(viewBounds.scale, viewBounds.scale))
  animComponent("yOffset"):SetInt(viewBounds.yOffset + 20 / viewBounds.scale)
end
